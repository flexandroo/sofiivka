import fs from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const sources = [
  "catalog/categories.js",
  "catalog/attribute-schema.js",
  "catalog/source-mappings.js",
  "catalog/normalize-products.js",
  "catalog/routing.js",
  "catalog/catalog-facade.js",
  "catalog/pdp-engine.js",
  "catalog/search-engine.js"
];

const sections = await Promise.all(sources.map(async source => {
  const content = await fs.readFile(path.join(root, source), "utf8");
  return `/* Source: ${source} */\n${content.trim()}\n`;
}));

await fs.writeFile(
  path.join(root, "catalog-data.js"),
  `/* Generated by scripts/build-catalog-data.mjs. Edit catalog/*.js source modules instead. */\n${sections.join("")}`
);

console.log(`Built catalog-data.js from ${sources.length} source modules.`);
